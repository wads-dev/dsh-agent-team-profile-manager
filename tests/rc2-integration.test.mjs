import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Context } from '@deepseek-ai/cordis';
import AgentLoop from '@deepseek-ai/dsh-agent-loop';
import { mountAgentLoopTestDependencies } from '@deepseek-ai/dsh-agent-loop-testkit';
import * as Persistence from '@deepseek-ai/dsh-session-persistence-jsonl';
import FsLocal from '@deepseek-ai/dsh-fs-local';
import WorkingDirectory from '@deepseek-ai/dsh-working-directory';
import Subagents from '@deepseek-ai/dsh-subagent';
import * as Spawn from '@deepseek-ai/dsh-subagent-spawn-in-process';
import Teams from '@deepseek-ai/dsh-agent-team';
import * as SubagentTool from '@deepseek-ai/dsh-tool-subagent';
import * as Router from '../lib/index.js';
import { SessionId } from '@deepseek-ai/dsh-session';
import { MockAdapter, textResponse } from './adapter.mjs';
import { TestSessionQuery } from './query.mjs';
const signal=new AbortController().signal;
test('rc.4 real subagent creation and runtime switch retain identity',async t=>{
 const ctx=new Context();t.after(()=>ctx.fiber.dispose());
 await mountAgentLoopTestDependencies(ctx);
 const root=await mkdtemp(join(tmpdir(),'profile-rc2-'));
 await ctx.plugin(Persistence,{root});await ctx.plugin(TestSessionQuery);
 await ctx.plugin(AgentLoop,{agents:[]});await ctx.plugin(FsLocal);await ctx.plugin(WorkingDirectory,{defaultDirectory:root});
 await ctx.plugin(Subagents);await ctx.plugin(Spawn,{providerName:'spawn'});await ctx.plugin(Teams,{defaultEnabled:true});await ctx.plugin(SubagentTool,{provider:'spawn',toolName:'subagent',modelSelection:true});
 const adapter=new MockAdapter([textResponse('initial'),textResponse('after switch')]);
 adapter.resolveModel=async(provider,model)=>({provider,id:model,name:model});
 ctx.llm.registerAdapter(['one','two'],adapter);
 await ctx.plugin(Router);
 const lead=await ctx.agentLoop.create(SessionId('lead'),{provider:'one',model:'A'});
 lead.session.append('subagent/model-selection-policy',{allowedModels:[{provider:'one',model:'A'},{provider:'two',model:'B'}]});
 const launch=ctx.tools.get('subagent',lead);assert.ok(launch.parameters.properties.provider);
 const batch=await ctx.tools.execute({agent:lead,signal,calls:[{type:'tool-call',id:'launch',name:'subagent',arguments:JSON.stringify({name:'worker',description:'Test',prompt:'First',provider:'one',model:'A'})}]});
 assert.equal(batch.results[0].result.isError,false,JSON.stringify(batch));
 const id=await ctx.subagents.resolveName(lead,'worker',signal); const child=ctx.agents.get(id);assert.ok(child);
 const rename=await ctx.tools.execute({agent:lead,signal,log:{turn:0,step:0},calls:[{type:'tool-call',id:'rename',name:'set_teammate_display_name',arguments:JSON.stringify({target:'worker',display_name:'Revisão Ágil'})}]});
 assert.equal(rename.results[0].result.isError,false,JSON.stringify(rename));
 assert.equal(ctx.sessionProjections.snapshot(lead.session).values.agentTeamDisplayNames[id],'Revisão Ágil');
 assert.equal(await ctx.subagents.resolveName(lead,'worker',signal),id);
 const switched=await ctx.tools.execute({agent:lead,signal,calls:[{type:'tool-call',id:'switch',name:'switch_teammate_model',arguments:JSON.stringify({teammate:'worker',provider:'two',model:'B'})}]});
 assert.equal(switched.results[0].result.isError,false,JSON.stringify(switched)); const result=switched.results[0].result.value;
 assert.equal(result.session,id);assert.equal(result.next.model,'B');
 assert.equal(child.model.current().model,'B');
 const forbidden=await ctx.tools.execute({agent:lead,signal,calls:[{type:'tool-call',id:'forbidden',name:'switch_teammate_model',arguments:JSON.stringify({teammate:'worker',provider:'two',model:'C'})}]});
 assert.equal(forbidden.results[0].result.isError,true);assert.equal(child.model.current().model,'B');
 const unknown=await ctx.tools.execute({agent:lead,signal,calls:[{type:'tool-call',id:'unknown',name:'switch_teammate_model',arguments:JSON.stringify({teammate:'not-a-member',provider:'two',model:'B'})}]});
 assert.equal(unknown.results[0].result.isError,true);
 assert.ok(ctx.tools.get('set_teammate_display_name',lead));
 child.cancel({kind:'user'});
});
